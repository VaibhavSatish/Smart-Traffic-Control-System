from pathlib import Path
import sys

import matplotlib.pyplot as plt
import pandas as pd

REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
if str(REPOSITORY_ROOT) not in sys.path:
    sys.path.insert(0, str(REPOSITORY_ROOT))

from evaluation.output_paths import RESULTS_ROOT, create_run_directory


def find_comparison_results():
    candidates = sorted(
        RESULTS_ROOT.glob("controller_comparison_*/comparison_results.csv"),
        key=lambda path: path.stat().st_mtime,
        reverse=True,
    )
    if candidates:
        return candidates[0]

    # Support comparison data generated by earlier versions of the scripts.
    legacy_path = RESULTS_ROOT / "comparison_results.csv"
    if legacy_path.exists():
        return legacy_path
    raise FileNotFoundError(
        "No comparison_results.csv found. Run evaluation/run_comparison.py first."
    )


def plot_comparison():
    results_path = find_comparison_results()
    output_dir = create_run_directory("comparison_plots")
    df = pd.read_csv(results_path)

    metrics = [
        ("avg_vehicle_waiting_time", "Average Vehicle Waiting Time"),
        ("avg_stopped", "Average Stopped Vehicles"),
        ("avg_speed", "Average Speed"),
        ("total_reward", "Total Reward"),
    ]
    controllers = ["Q-learning", "Fixed-time"]

    for metric, title in metrics:
        means = df.groupby("controller")[metric].mean().reindex(controllers)
        stds = df.groupby("controller")[metric].std().reindex(controllers)

        plt.figure(figsize=(8, 5))
        plt.bar(controllers, means, yerr=stds, capsize=5)
        plt.title(title)
        plt.ylabel(title)
        plt.tight_layout()

        filename = output_dir / f"{metric}_comparison.png"
        plt.savefig(filename, dpi=300)
        plt.close()
        print(f"Saved {filename}")

    print(f"Comparison data loaded from {results_path}")


if __name__ == "__main__":
    plot_comparison()
